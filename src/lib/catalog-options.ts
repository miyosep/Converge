export const catalogOptions: CatalogOption[] = [
  ...restaurantOptions.map((r) => ({
    ...r,
    category: "restaurant" as const,
    kind: r.cuisine,
    facilities: [],
  })),
  ...Object.entries(seeds).flatMap(([category, entries]) =>
    entries.map(
      (
        [name, kind, area, price, deposit, capacity, facilities, beds],
        index,
      ) => ({
        id: `${category}-${String(index + 1).padStart(2, "0")}`,
        category: category as Category,
        name,
        kind,
        area,
        price,
        deposit,
        capacity,
        facilities,
        ...(beds === undefined ? {} : { beds }),
        wheelchairAccessible: index % 3 === 0,
      }),
    ),
  ),
];
export function optionsForCategory(category: Category) {
  return catalogOptions.filter((option) => option.category === category);
}
export function categoryForIds(ids: readonly string[]): Category {
  return (
    catalogOptions.find((option) => option.id === ids[0])?.category ??
    "restaurant"
  );
}
export function candidateLabel(id: string) {
  return catalogOptions.find((option) => option.id === id)?.name ?? id;
}
